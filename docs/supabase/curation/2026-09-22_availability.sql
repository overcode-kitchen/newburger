-- 취급 한정 표시 (2026-09-22)
--
-- 브랜드 사이트에 있다고 전 매장에서 파는 게 아니다. 모르고 가면 헛걸음이 되므로 화면에 밝힌다.
-- 맘스터치 앱에서 이 메뉴들이 안 보이는 것도 같은 이유 — 앱은 매장을 먼저 고르게 하고,
-- 선택한 매장이 미취급점이면 메뉴가 나오지 않는다.

-- 스매쉬 3종 · 그릴드 2종 — "철판 조리 시설을 갖춘 전국 1000여개 비프버거 판매점"에서만 판매
-- (핀포인트뉴스 2026-09-09). 맘스터치 전 매장은 1,400개 이상이라 일부에만 있다.
update menus
set curated_availability = '비프버거 판매점에서만 팔아요 (전국 1,000여 곳)'
where brand = 'moms'
  and (name like '%스매쉬버거%' or name like '그릴드버거%' or name like '그릴드베이컨버거%');

-- 내슈빌핫치킨버거 — 기간 한정 + 한정 수량, 조기 품절 가능 (신아일보 2026-08-10)
update menus
set curated_availability = '한정 수량이라 일찍 품절될 수 있어요'
where brand = 'moms' and name like '내슈빌핫치킨버거%';
